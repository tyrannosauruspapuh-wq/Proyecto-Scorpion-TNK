Mycropython
01
Instalar Thonny IDE
Descargue e instale Thonny desde su página oficial para tener un entorno Python sencillo.
https://thonny.org
Descargue el instalador para tu sistema operativo (Windows, macOS, Linux)
Ejecute el instalador y siga las instrucciones
Abra Thonny para verificar que funciona

02
Instale dependencias en Thonny
Use el gestor de paquetes integrado para instalar librerías de Python.
Abra Thonny
Valla a Herramientas → Administrar paquetes
Escribe el nombre de la librería (ej. numpy, matplotlib, pandas)
Haga clic en Instalar
Verifique la instalación importando la librería en un script


FPGA
01
Instalar Gowin IDE
Descargue e instale Gowin IDE para trabajar con FPGA.
https://www.gowinsemi.com/en/support/download_ide/
Descargue la versión adecuada para tu sistema operativo
Instale siguiendo las instrucciones del asistente
Abra Gowin IDE para confirmar que se ejecuta correctamente

02
Configurar dependencias en Gowin IDE
Instale los paquetes necesarios para síntesis y simulación de proyectos FPGA.
Durante la instalación seleccione los paquetes de síntesis y simulación
Verifique que se instalen los drivers USB para tu placa (ej. Tang Nano)
En Project → Device seleccione tu FPGA
Asegúrese de que los módulos de simulación (Verilog/VHDL) estén habilitados
